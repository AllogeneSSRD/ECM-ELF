inline Value phi(Value d) {
    Value result=d;
    for(Value prime=2;prime*prime<=d;++prime)if(d%prime==0) {
        do {d/=prime;}while(d%prime==0);result-=result/prime;
    }
    return d>1?result-result/d:result;
}
