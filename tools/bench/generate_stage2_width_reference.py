"""Freeze existing validated curve evidence as no-user-tune width references.

Reads retained logs, never executes ECM or changes the evidence. GPU phase
frequency normalization is an explicit estimate, not a new measurement.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[2]


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--wide',type=Path,default=ROOT/'data/experiments/stage2_tuned_carrier_final_20261011/measurements.json')
    p.add_argument('--pair',type=Path,default=ROOT/'data/experiments/stage2_resume_tune_20261013/m12011_pair/report.json')
    p.add_argument('--output',type=Path,default=ROOT/'src/ecm/service/planning/ecm_stage2_width_reference.h')
    args=p.parse_args();wide=json.loads(args.wide.read_text(encoding='utf-8'));pair=json.loads(args.pair.read_text(encoding='utf-8'))
    if not wide['complete'] or not pair['passed']:raise ValueError('reference evidence incomplete')
    records=[]
    stages={'baby':'Build baby-point F tree','ftree':'Prepare polynomial inverse',
            'inverse':'Giant points, G trees and fold','descent':'Accumulate leaf products and GCD',
            'accum':'Validate arithmetic and finalize factors','loop':'Normalize fold and descend F tree'}
    for r in wide['runs']:
        if r['category']=='warmup' or r['B2']!=max(wide['bounds']):continue
        log=Path(r['log']);raw=log.read_bytes()
        if hashlib.sha256(raw).hexdigest()!=r['log_sha256']:raise ValueError('reference log changed')
        if r['wall']['clean']!='1' or r['result']['bad_factors']:raise ValueError('unclean curve reference')
        text=raw.decode('utf-8',errors='replace')
        phases={name:float(value) for name,value in re.findall(r'stage2_phase: (.+?) previous=([\d.]+) s',text)}
        values={k:phases[v] for k,v in stages.items()}
        gpu=sum(values[k] for k in ('baby','ftree','inverse','descent','loop'))
        for k in ('baby','ftree','inverse','descent','loop'):values[k]*=2400/1800
        split=r['stats']['real_batched_split']
        for k in ('giant','trees','fold'):values[k]=float(split['gtrees' if k=='trees' else k])
        bits=int(r['shape']['S_bits']);degree=r['P'];capacity=(256<<20)//(((bits+63)//64)*16)
        records.append(dict(target_bits=r['bits'],arithmetic_bits=bits,b1=r['B1'],b2=r['B2'],d=r['D'],
                            giant_chunk=max(1,(capacity+degree-1)//degree)*degree,batch_bytes=256<<20,
                            mersenne=r['arm']=='carrier',total=float(r['wall']['total'])+gpu/3,**values))
    for s in pair['summaries']:
        names={'baby':'phase_baby_seconds','ftree':'phase_ftree_seconds','inverse':'phase_inverse_setup_seconds',
               'descent':'phase_descent_seconds','accum':'phase_accum_seconds','loop':'phase_giant_loop_seconds',
               'giant':'giant_seconds','trees':'gtrees_seconds','fold':'fold_seconds'}
        records.append(dict(target_bits=s['target_bits'],arithmetic_bits=s['arithmetic_bits'],b1=s['b1'],b2=s['b2'],
                            d=s['d'],giant_chunk=s['giant_chunk_points'],batch_bytes=64<<20,
                            mersenne=s['modulus_kind']=='mersenne',total=s['median_seconds'],**{k:s[v] for k,v in names.items()}))
    records.sort(key=lambda r:(r['mersenne'],r['arithmetic_bits']))
    fields=['target_bits','arithmetic_bits','b1','b2','d','giant_chunk','batch_bytes','mersenne','total',*names]
    output=['#pragma once','// Generated by tools/bench/generate_stage2_width_reference.py from frozen evidence.',
            '// 4060 Laptop reference at 1800 MHz: 2400-MHz GPU phases are scaled by 4/3.',
            '// The scaling, phase mixture and unmeasured regions are estimates, not measurements.',
            '// Wide EXE: '+wide['executable_sha256'], '// Paired EXE: '+pair['identity']['exe_sha256'],
            '// Wide evidence SHA256: '+hashlib.sha256(args.wide.read_bytes()).hexdigest(),
            '// Paired evidence SHA256: '+hashlib.sha256(args.pair.read_bytes()).hexdigest(),
            'namespace ecm_stage2 { namespace tune { namespace portable {',
            'struct WidthReference {',
            '    unsigned target_bits,arithmetic_bits;',
            '    Word b1,b2,d,giant_chunk,batch_bytes;bool mersenne;',
            '    double total,baby,ftree,inverse,descent,accum,loop,giant,trees,fold;',
            '};','inline constexpr WidthReference width_references[]={']
    def literal(v):return ('true' if v else 'false') if isinstance(v,bool) else str(v) if isinstance(v,int) else format(v,'.17g')
    output.extend('    {'+','.join(literal(r[k]) for k in fields)+'},' for r in records)
    output+=['};','} } }','']
    args.output.write_text('\n'.join(output),encoding='utf-8')
    print(f'Frozen {len(records)} ordinary/Mersenne references: {args.output}')


if __name__=='__main__':main()
