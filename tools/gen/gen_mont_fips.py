#!/usr/bin/env python3
"""Generate stage1 FIPS Montgomery mul/sqr kernels for fixed bit-widths.

FIPS (Finely Integrated Product Scanning) uses 3 carry accumulators (t,u,v)
instead of a full limb array, eliminating register spill at large bit-widths.
Suitable for >=1024-bit where CIOS unroll overflows GPU VGPR limits.

Generates:
  kernels/opencl/mont_mul/mont_mul_fips_<W>b.cl
"""
import os, sys

ROOT = sys.argv[1] if len(sys.argv) > 1 else "kernels/opencl/mont_mul"
WIDTHS = [(1024, 32), (2048, 64)]  # (bit-width, limbs)

def emit_fips(limbs: int, bits: int) -> str:
    L = limbs
    Lp1 = L + 1
    L2 = 2 * L
    W = bits

    guard = f"MONT_FIXED_{W}_LIMBS"
    csa_name = f"fips_{W}_csa_add"
    shift_name = f"fips_{W}_csa_shift"
    fin_name = f"fips_{W}_finalize_p"
    mul_name = f"mont_mul_fips_{W}b"
    sqr_name = f"mont_sqr_fips_{W}b"

    out = []
    out.append(f"// AUTO-GENERATED by tools/gen_mont_fips.py - do not edit.")
    out.append(f"// FIPS Montgomery mul/sqr - {L} limbs ({W}-bit).")
    out.append(f"// 3-register carry accumulator; no t[] array, no spill.")
    out.append(f"")
    out.append(f"#ifndef {guard}")
    out.append(f"#define {guard} {L}u")
    out.append(f"#endif")
    out.append(f"")

    out.append(f"static inline void {csa_name}(uint *t, uint *u, uint *v, ulong prod) {{")
    out.append(f"    ulong val = (ulong)(*v) + prod;")
    out.append(f"    *v = (uint)val;")
    out.append(f"    val = (val >> 32) + (ulong)(*u);")
    out.append(f"    *u = (uint)val;")
    out.append(f"    val = (val >> 32) + (ulong)(*t);")
    out.append(f"    *t = (uint)val;")
    out.append(f"}}")
    out.append(f"")
    out.append(f"static inline void {shift_name}(uint *t, uint *u, uint *v) {{")
    out.append(f"    uint tv = *t; uint uv = *u;")
    out.append(f"    *v = uv; *u = tv; *t = 0u;")
    out.append(f"}}")
    out.append(f"")

    out.append(f"static inline void {fin_name}(uint *out, const uint *P, const uint *n) {{")
    out.append(f"    uint ps = P[{L}u];")
    out.append(f"    ulong borrow = 0ul;")
    out.append(f"    uint D[{L}u];")
    out.append(f"    for (uint i = 0u; i < {L}u; ++i) {{")
    out.append(f"        ulong tv = (ulong)P[i];")
    out.append(f"        ulong nv = (ulong)n[i];")
    out.append(f"        ulong w = tv - nv - borrow;")
    out.append(f"        D[i] = (uint)w;")
    out.append(f"        borrow = (tv < nv + borrow) ? 1ul : 0ul;")
    out.append(f"    }}")
    out.append(f"    uint any_high = (ps != 0u) ? 1u : 0u;")
    out.append(f"    uint need_sub = any_high | ((borrow == 0u) ? 1u : 0u);")
    out.append(f"    uint mask = 0u - need_sub;")
    out.append(f"    for (uint i = 0u; i < {L}u; ++i) {{")
    out.append(f"        out[i] = (D[i] & mask) | (P[i] & ~mask);")
    out.append(f"    }}")
    out.append(f"}}")
    out.append(f"")

    out.append(f"static inline void {mul_name}(uint *out, const uint *a, const uint *b,")
    out.append(f"                                            const uint *N, uint np0, uint limbs) {{")
    out.append(f"    uint P[{Lp1}u];")
    out.append(f"    uint t = 0u;")
    out.append(f"    uint u = 0u;")
    out.append(f"    uint v = 0u;")
    out.append(f"")
    out.append(f"    for (uint i = 0u; i < {L}u; ++i) {{")
    out.append(f"        for (uint j = 0u; j < i; ++j) {{")
    out.append(f"            {csa_name}(&t, &u, &v, (ulong)a[j] * (ulong)b[i - j]);")
    out.append(f"            {csa_name}(&t, &u, &v, (ulong)P[j] * (ulong)N[i - j]);")
    out.append(f"        }}")
    out.append(f"        {csa_name}(&t, &u, &v, (ulong)a[i] * (ulong)b[0]);")
    out.append(f"        uint pi = (uint)((ulong)v * (ulong)np0);")
    out.append(f"        {csa_name}(&t, &u, &v, (ulong)pi * (ulong)N[0]);")
    out.append(f"        P[i] = pi;")
    out.append(f"        {shift_name}(&t, &u, &v);")
    out.append(f"    }}")
    out.append(f"")
    out.append(f"    for (uint i = {L}u; i < {L2}u; ++i) {{")
    out.append(f"        for (uint j = i - {L}u + 1u; j < {L}u; ++j) {{")
    out.append(f"            {csa_name}(&t, &u, &v, (ulong)a[j] * (ulong)b[i - j]);")
    out.append(f"            {csa_name}(&t, &u, &v, (ulong)P[j] * (ulong)N[i - j]);")
    out.append(f"        }}")
    out.append(f"        P[i - {L}u] = v;")
    out.append(f"        {shift_name}(&t, &u, &v);")
    out.append(f"    }}")
    out.append(f"    P[{L}u] = v;")
    out.append(f"")
    out.append(f"    {fin_name}(out, P, N);")
    out.append(f"    (void)np0;")
    out.append(f"}}")
    out.append(f"")

    out.append(f"static inline void {sqr_name}(uint *out, const uint *a, const uint *N, uint np0, uint limbs) {{")
    out.append(f"    {mul_name}(out, a, a, N, np0, limbs);")
    out.append(f"}}")
    out.append(f"")

    return "\n".join(out)

os.makedirs(ROOT, exist_ok=True)
for bits, limbs in WIDTHS:
    path = os.path.join(ROOT, f"mont_mul_fips_{bits}b.cl")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(emit_fips(limbs, bits))
    print(f"Wrote {path}")
