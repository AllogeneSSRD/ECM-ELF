#!/usr/bin/env python3
"""Generate stage1 Montgomery mul/sqr unrolled kernels (auto loop + manual straight-line).

For each width: A active 32-bit limbs inside a C-limb container (zero-fill A..C-1).
 - auto:   #pragma unroll loops  -> mont_mul/mont_mul_unroll_<W>b.cl        (desktop/non-Android)
 - manual: constant-index form   -> mont_mul/mont_mul_unroll_manual_<W>b.cl (Android; Adreno reg-promotes)
Both are CIOS Montgomery multiply, bit-exact (verified against a bignum reference).
"""
import os, sys
WIDTHS = [(192,6,6),(256,8,8),(384,12,12),(512,16,16),(768,24,24),(1024,32,32),
         (1536,48,48),(2048,64,64),(2560,80,80),(3072,96,96),(3584,112,112),
         (4096,128,128),(4608,144,144),(5120,160,160),(5632,176,176),
         (6144,192,192),(6656,208,208),(7168,224,224),(7680,240,240),(8192,256,256)]
ROOT = sys.argv[1] if len(sys.argv)>1 else "kernels/opencl/mont_mul"

def body(stem, A, C, manual):
    mul = f"mont_mul_{stem}"; sqr = f"mont_sqr_{stem}"
    L=[]
    if manual:
        L.append(f"// Stage1 Montgomery mul/sqr - {A*32 if C==A else 'N'}<= {A} active limbs in {C}-limb container.")
        L.append("// Manual constant-index straight-line unroll (scalar variables for mobile GPU register promotion).")
        L.append("// AUTO-GENERATED by tools/gen_mont_unroll.py - do not edit.")
        L.append(f"static inline void {mul}(uint *out, const uint *a, const uint *b, const uint *N, uint np0, uint limbs) {{")
        # scalar t variables instead of array — forces register allocation
        L.append("    uint " + ", ".join(f"t_{k}" for k in range(A+2)) + ";")
        L.append("    " + " ".join(f"t_{k}=0u;" for k in range(A+2)))
        L.append("    uint " + ", ".join(f"B_{j}" for j in range(C)) + ";")
        L.append("    " + " ".join(f"B_{j}=b[{j}];" for j in range(C)))
        L.append("    uint ai; ulong carry, uv, top; uint m;")
        for i in range(A):
            L.append(f"    ai=a[{i}]; carry=0ul;")
            for j in range(A):
                L.append(f"    uv=(ulong)t_{j}+(ulong)ai*(ulong)B_{j}+carry; t_{j}=(uint)uv; carry=uv>>32;")
            L.append(f"    top=(ulong)t_{A}+carry; t_{A}=(uint)top; t_{A+1}=(uint)(top>>32);")
            L.append(f"    m=(uint)((ulong)t_0*(ulong)np0); carry=0ul;")
            for j in range(A):
                st=f" t_{j-1}=(uint)uv;" if j>0 else ""
                L.append(f"    uv=(ulong)t_{j}+(ulong)m*(ulong)N[{j}]+carry;{st} carry=uv>>32;")
            L.append(f"    top=(ulong)t_{A}+carry; t_{A-1}=(uint)top; top=(ulong)t_{A+1}+(top>>32); t_{A}=(uint)top; t_{A+1}=(uint)(top>>32);")
        L.append("    ulong borrow=0ul; ulong w;")
        for i in range(A):
            L.append(f"    w=(ulong)t_{i}-(ulong)N[{i}]-borrow; borrow=((ulong)t_{i}<(ulong)N[{i}]+borrow)?1ul:0ul;")
        L.append(f"    uint need_sub=(t_{A}|t_{A+1})!=0u?1u:0u; need_sub=(borrow==0u)?1u:need_sub; uint mask=0u-need_sub;")
        L.append("    borrow=0ul;")
        for i in range(A):
            L.append(f"    w=(ulong)t_{i}-(ulong)N[{i}]-borrow; out[{i}]=((uint)w&mask)|(t_{i}&~mask); borrow=((ulong)t_{i}<(ulong)N[{i}]+borrow)?1ul:0ul;")
        if C>A: L.append("    " + " ".join(f"out[{i}]=0u;" for i in range(A,C)))
        L.append("    (void)limbs;")
        L.append("}")
    else:
        # NVIDIA: large-width unrolled mont_mul may crash the compiler.
        # A>=128 (4096b+): _Pragma platform guard (AMD full, NVIDIA unroll 32).
        # 3072b-3584b (96-112 limbs) handle full unroll fine on both platforms.
        if A >= 128:
            unroll_block = (
                "#if defined(__AMDGCN__)\n"
                "#define MONT_UNROLL _Pragma(\"unroll\")\n"
                "#else\n"
                "#define MONT_UNROLL _Pragma(\"unroll 32\")\n"
                "#endif\n"
            )
            pu = "    MONT_UNROLL\n"
        else:
            unroll_block = ""
            pu = "    #pragma unroll\n"
        L.append(f"// Stage1 Montgomery mul/sqr - {A} active limbs in {C}-limb container.")
        L.append("// Inner #pragma unroll for SRA; outer loop kept as-is for fast compile.")
        L.append("// AUTO-GENERATED by tools/gen_mont_unroll.py - do not edit.")
        L.append(f"static inline void {mul}(uint *out, const uint *a, const uint *b, const uint *N, uint np0, uint limbs) {{")
        if unroll_block:
            L.append(unroll_block.rstrip("\n"))
        L.append(f"    uint t[{A}u+2u];")
        L.append(pu+f"    for (uint i = 0u; i < {A}u + 2u; ++i) t[i] = 0u;")
        L.append(f"    uint B[{C}u];")
        L.append(pu+f"    for (uint j = 0u; j <{C}u; ++j) B[j] = b[j];")
        L.append(f"    for (uint i = 0u; i <{A}u; ++i) {{")
        L.append("        uint ai = a[i]; ulong carry = 0ul, uv;")
        L.append(pu+f"        for (uint j = 0u; j < {A}u; ++j) {{\n\
            uv = (ulong)t[j] + (ulong)ai * (ulong)B[j] + carry;\n\
            t[j] = (uint)uv; carry = uv>>32;\n\
        }}")
        L.append(f"        ulong top = (ulong)t[{A}u] + carry;")
        L.append(f"        t[{A}u]    = (uint)top;")
        L.append(f"        t[{A}u+1u] = (uint)(top>>32);")
        L.append(f"        uint m = (uint)((ulong)t[0] * (ulong)np0);")
        L.append(f"        uv = (ulong)t[0] + (ulong)m * (ulong)N[0]; carry = uv>>32;")
        L.append(pu+f"        for (uint j = 1u; j < {A}u; ++j) {{")
        L.append(f"            uv = (ulong)t[j] + (ulong)m * (ulong)N[j] + carry;\n\
            t[j-1u] = (uint)uv; carry = uv>>32;\n\
            }}")
        L.append(f"        top = (ulong)t[{A}u] + carry;\n\
        t[{A}u-1u] = (uint)top;\n\
        top = (ulong)t[{A}u + 1u] + (top>>32);\n\
        t[{A}u]    = (uint)top;\n\
        t[{A}u+1u] = (uint)(top>>32);")
        L.append("    }")
        L.append(f"    ulong borrow = 0ul;")
        L.append(f"    uint D[{A}u];")
        L.append(pu+f"    for (uint i = 0u;i<{A}u;++i) {{\n\
            ulong tv = (ulong)t[i], nv = (ulong)N[i];\n\
            ulong w = tv - nv - borrow;\n\
            D[i] = (uint)w;\n\
            borrow = (tv < nv + borrow) ? 1ul : 0ul;\n\
        }}")
        L.append(f"        uint need_sub = (t[{A}u] | t[{A}u+1u]) != 0u ? 1u : 0u;\n\
        need_sub  = (borrow == 0u) ? 1u : need_sub;\n\
        uint mask = 0u - need_sub;")
        L.append(pu+f"    for (uint i = 0u; i < {A}u; ++i) out[i] = (D[i] & mask) | (t[i] & ~mask);")
        if C>A: L.append(pu+f"    for (uint i={A}u;i<{C}u;++i) out[i]=0u;")
        L.append("    (void)limbs;")
        L.append("}")
    L.append("")
    L.append(f"static inline void {sqr}(uint *out, const uint *a, const uint *N, uint np0, uint limbs) {{")
    L.append(f"    {mul}(out, a, a, N, np0, limbs);")
    L.append("}")
    return "\n".join(L)+"\n"

def body_local(stem, A, C):
    """Generate a __local-memory variant that receives t_local / B_local as LDS pointers."""
    mul = f"mont_mul_{stem}_local"; sqr = f"mont_sqr_{stem}_local"
    # NVIDIA compiler crashes with full unroll on __local code at A>=48.
    # Threshold is lower than body() because LDS accesses have higher latency
    # than private registers — full unroll helps less AND bloats code more.
    if A >= 48:
        unroll_pragma = (
            "#if defined(__AMDGCN__)\n"
            "#define LOCAL_UNROLL _Pragma(\"unroll\")\n"
            "#else\n"
            "#define LOCAL_UNROLL _Pragma(\"unroll 32\")\n"
            "#endif\n"
        )
        pu = "    LOCAL_UNROLL\n"
    else:
        unroll_pragma = ""
        pu = "    #pragma unroll\n"
    L = []
    L.append(f"// Stage1 Montgomery mul/sqr LDS variant - {A} active limbs in {C}-limb container.")
    L.append("// __local t[]/B[] buffers provided by caller to avoid scratch-memory spill.")
    L.append("// AUTO-GENERATED by tools/gen_mont_unroll.py - do not edit.")
    L.append(f"static inline void {mul}(uint *out, const uint *a, const uint *b, const uint *N,")
    L.append(f"    uint np0, uint limbs, __local uint *t_local, __local uint *B_local) {{")
    if unroll_pragma:
        L.append(unroll_pragma.rstrip("\n"))
    L.append(pu + f"    for (uint i = 0u; i < {A}u + 2u; ++i) t_local[i] = 0u;")
    L.append(pu + f"    for (uint j = 0u; j <{C}u; ++j) B_local[j] = b[j];")
    L.append(f"    for (uint i = 0u; i <{A}u; ++i) {{")
    L.append("        uint ai = a[i]; ulong carry = 0ul, uv;")
    L.append(pu + f"        for (uint j = 0u; j < {A}u; ++j) {{\n\
            uv = (ulong)t_local[j] + (ulong)ai * (ulong)B_local[j] + carry;\n\
            t_local[j] = (uint)uv; carry = uv>>32;\n\
        }}")
    L.append(f"        ulong top = (ulong)t_local[{A}u] + carry;")
    L.append(f"        t_local[{A}u]    = (uint)top;")
    L.append(f"        t_local[{A}u+1u] = (uint)(top>>32);")
    L.append(f"        uint m = (uint)((ulong)t_local[0] * (ulong)np0);")
    L.append(f"        uv = (ulong)t_local[0] + (ulong)m * (ulong)N[0]; carry = uv>>32;")
    L.append(pu + f"        for (uint j = 1u; j < {A}u; ++j) {{")
    L.append(f"            uv = (ulong)t_local[j] + (ulong)m * (ulong)N[j] + carry;\n\
            t_local[j-1u] = (uint)uv; carry = uv>>32;\n\
            }}")
    L.append(f"        top = (ulong)t_local[{A}u] + carry;\n\
        t_local[{A}u-1u] = (uint)top;\n\
        top = (ulong)t_local[{A}u + 1u] + (top>>32);\n\
        t_local[{A}u]    = (uint)top;\n\
        t_local[{A}u+1u] = (uint)(top>>32);")
    L.append("    }")
    L.append(f"    ulong borrow = 0ul;")
    L.append(f"    uint D[{A}u];")
    L.append(pu + f"    for (uint i = 0u;i<{A}u;++i) {{\n\
            ulong tv = (ulong)t_local[i], nv = (ulong)N[i];\n\
            ulong w = tv - nv - borrow;\n\
            D[i] = (uint)w;\n\
            borrow = (tv < nv + borrow) ? 1ul : 0ul;\n\
        }}")
    L.append(f"        uint need_sub = (t_local[{A}u] | t_local[{A}u+1u]) != 0u ? 1u : 0u;\n\
        need_sub  = (borrow == 0u) ? 1u : need_sub;\n\
        uint mask = 0u - need_sub;")
    L.append(pu + f"    for (uint i = 0u; i < {A}u; ++i) out[i] = (D[i] & mask) | (t_local[i] & ~mask);")
    if C > A: L.append(pu + f"    for (uint i={A}u;i<{C}u;++i) out[i]=0u;")
    L.append("    (void)limbs;")
    L.append("}")
    L.append("")
    L.append(f"static inline void {sqr}(uint *out, const uint *a, const uint *N, uint np0, uint limbs,")
    L.append(f"        __local uint *t_local, __local uint *B_local) {{")
    L.append(f"    {mul}(out, a, a, N, np0, limbs, t_local, B_local);")
    L.append("}")
    return "\n".join(L) + "\n"

os.makedirs(ROOT, exist_ok=True)
# Widths not in SKIP_AUTO have hand-crafted non-_local kernels managed manually.
SKIP_AUTO = {4096}
for (W,A,C) in WIDTHS:
    if W not in SKIP_AUTO:
        open(os.path.join(ROOT,f"mont_mul_unroll_{W}b.cl"),"w").write(body(f"unroll_{W}b",A,C,manual=False))
    open(os.path.join(ROOT,f"mont_mul_unroll_{W}b_local.cl"),"w").write(body_local(f"unroll_{W}b",A,C))
    print(f"wrote {W}b auto{'' if W in SKIP_AUTO else '+local'} (A={A},C={C})")
