"""Compose editable battlesuit SVG layers with the pinned Ely rig, offline.

Produces complete 7x8 animation sheets using the existing atlas renderer.
The local reference pictures guide the new drawings; they are never loaded by
the runtime or required to regenerate the checked-in SVG source.
"""
from pathlib import Path
import argparse,copy,hashlib,json,struct,xml.etree.ElementTree as ET
from generate_gui_v2_pet import layers,frame

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'assets/gui_v2/skins'
MOODS=['Calm','Working','Waiting','Error','Done','Doze','Wink']
ET.register_namespace('', 'http://www.w3.org/2000/svg')

def digest(path):return hashlib.sha256(path.read_bytes().replace(b'\r\n',b'\n')).hexdigest()

def catalog():
    value=json.loads((SOURCE/'manifest.json').read_text(encoding='utf-8'))
    assert value['schema']==1 and len(value['skins'])==3
    assert len({v['id'] for v in value['skins']})==3
    for skin in value['skins']:
        assert skin['id'].isascii() and all(c.islower() or c=='_' for c in skin['id'])
        assert skin['atlas']==f'pet_ely_{skin["id"]}.png'
    return value

def compose(base,spec,skin):
    additions={}
    for svg in [skin['svg'],spec['shared_svg']]:
        for group in ET.parse(SOURCE/svg).getroot():
            anchor=group.attrib['data-before'];bone='Bone::'+group.attrib['data-bone']
            pivot=[float(n) for n in group.attrib.get('data-pivot','256 236').split()]
            name=skin['id']+'-'+group.attrib['id']
            children=''.join(ET.tostring(n,encoding='unicode') for n in group)
            additions.setdefault(anchor,[]).append(dict(name=name,color=0xffffff,alpha=1,frame=[110,-36,292,323],pivot=pivot,bone=bone,shapes=children))
    known={p['name'] for p in base};assert set(additions)<=known
    result=[]
    for part in copy.deepcopy(base):
        result.extend(additions.get(part['name'],[]))
        if part['name'] in spec['remove_layers']:continue
        key='iris' if part['name'].startswith('iris-') else 'iris-ring' if part['name'].startswith('ring-') else part['name']
        if key in skin['palette']:part['color']=int(skin['palette'][key][1:],16)
        result.append(part)
    return result

def registry(spec):
    rows=[dict(id='classic',english='Classic ELY',chinese='经典 ELY',atlas='pet_ely.png'),*spec['skins']]
    lines=['// Generated by tools/gen/generate_gui_v2_pet_skins.py; edit assets/gui_v2/skins/manifest.json.',
           '#pragma once','#include <array>','#include <string_view>','namespace ecmgui_v2::pet {',
           'struct Skin {const char *id,*english,*chinese,*atlas;};',
           'inline constexpr std::array<Skin,4> skins{{']
    for row in rows:lines.append('    {'+','.join(json.dumps(row[key],ensure_ascii=True) for key in ['id','english','chinese','atlas'])+'},')
    lines+=['}};','inline const Skin* find_skin(std::string_view id){for(const auto& skin:skins)if(id==skin.id)return &skin;return nullptr;}','}']
    return '\n'.join(lines)+'\n'

def prepare(spec,skin,out,base):
    out.mkdir(parents=True,exist_ok=False)
    parts=compose(base,spec,skin)
    styles=';'.join('--'+k+':'+v for k,v in skin['palette'].items())
    svgs=[frame(parts,mood,i).replace(' width="224"',f' style="{styles}" width="224"',1) for mood in MOODS for i in range(8)]
    html='<!doctype html><meta charset="utf-8"><style>html,body{margin:0;background:transparent}main{display:grid;grid-template-columns:repeat(8,224px);width:1792px}svg{display:block}</style><main>'+''.join(svgs)+'</main>'
    (out/'atlas.html').write_text(html,encoding='utf-8',newline='\n')
    sources=['assets/gui_v2/skins/manifest.json','assets/gui_v2/skins/'+spec['shared_svg'],'assets/gui_v2/skins/'+skin['svg'],'tools/gen/generate_gui_v2_pet_skins.py','tools/gen/generate_gui_v2_pet.py','tools/gen/render_gui_v2_pet.cjs']
    metadata=dict(columns=8,rows=7,frame_width=224,frame_height=248,logical_width=112,logical_height=124,moods=MOODS,
                  skin=skin['id'],english=skin['english'],chinese=skin['chinese'],wiki=skin['wiki'],
                  source_sha256=digest(ROOT/'third_party/gui_v2_pet/rig.rs'),source_normalization='LF only',
                  source_files_sha256={name:digest(ROOT/name) for name in sources},layers=len(parts),reference_files=skin['reference_files'],
                  provenance='Project-authored SVG costume/hair layers based on user-supplied character references; facial animation derived from pinned ELYTerminal MIT rig. Not an extracted game asset.')
    (out/'metadata.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\n')

def main():
    p=argparse.ArgumentParser();p.add_argument('--out',type=Path);p.add_argument('--check',action='store_true');p.add_argument('--record',action='store_true');a=p.parse_args()
    spec=catalog();header=ROOT/'src/ecm/application/gui_v2/generated/pet_skins.h';expected=registry(spec)
    receipt=ROOT/'config/gui_v2_pet_skins.generated.json'
    if a.check:
        assert header.read_bytes()==expected.encode(),'Stale pet skin registry'
        for name,value in json.loads(receipt.read_text(encoding='utf-8'))['sha256'].items():
            assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==value,'Stale pet skin asset/source: '+name
        print('Pet skin registry, source and atlases current');return
    header.write_text(expected,encoding='utf-8',newline='\n')
    if a.out:
        a.out.mkdir(parents=True,exist_ok=False)
        source=ROOT/'third_party/gui_v2_pet/rig.rs';assert digest(source)=='c34e9274cf77d8011eee331d91f3ea7869a619f9fc72266a85ff7a9ad6a9cca6'
        base=layers(source.read_text(encoding='utf-8'))
        for skin in spec['skins']:prepare(spec,skin,a.out/skin['id'],base)
        print('Prepared three SVG skins, 7 states x 8 frames each')
    if a.record:
        names={header.relative_to(ROOT).as_posix(),'third_party/gui_v2_pet/rig.rs'}
        for skin in spec['skins']:
            image=ROOT/'assets/gui_v2'/skin['atlas'];metadata=image.with_suffix('.json');data=json.loads(metadata.read_text(encoding='utf-8'))
            assert image.stat().st_size<8388608 and image.read_bytes()[:8]==b'\x89PNG\r\n\x1a\n'
            assert struct.unpack('>II',image.read_bytes()[16:24])==(1792,1736)
            assert hashlib.sha256(image.read_bytes()).hexdigest()==data['png_sha256']
            assert data['skin']==skin['id'] and data['english']==skin['english'] and data['moods']==MOODS
            for name,value in data['source_files_sha256'].items():assert digest(ROOT/name)==value,'Regenerate stale skin: '+name
            names.update(data['source_files_sha256']);names.update([image.relative_to(ROOT).as_posix(),metadata.relative_to(ROOT).as_posix()])
        receipt.write_text(json.dumps({'sha256':{name:hashlib.sha256((ROOT/name).read_bytes()).hexdigest() for name in sorted(names)}},indent=2)+'\n',encoding='utf-8',newline='\n')
        print('Recorded skin source and output fingerprints')

if __name__=='__main__':main()
