#!/usr/bin/env python3
"""Generate fused v_mul blocks + C ulong carry chain for mont mul CIOS."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "kernels/opencl/bench/mont_mul_asm_block8_generated.cl"

HEADER = """// AUTO-GENERATED by tools/gen_mont_mul_asm_block8.py —do not edit.

#if defined(MONT_MUL_ASM_ENABLE) && defined(__AMDGCN__)

"""


def emit_mul_block8(fn_name: str, a_sym: str, arr_sym: str, t_load: list[int], t_store: list[int], b_idx: list[int]) -> str:
    n = len(t_load)
    lines = [
        f"static inline ulong {fn_name}(\n",
        f"    ulong carry, uint {a_sym}, uint *t, uint *{arr_sym})\n",
        "{\n",
    ]
    for j in range(n):
        lines.append(f"    uint plo{j}, phi{j};\n")
    for j in range(n):
        lines.append(f"    uint b{j} = {arr_sym}[{b_idx[j]}];\n")
        lines.append(f"    uint tj{j} = t[{t_load[j]}];\n")

    asm = []
    for j in range(n):
        asm.append(f"v_mul_lo_u32    %[plo{j}], %[{a_sym}], %[b{j}]\\n\\t")
        asm.append(f"v_mul_hi_u32    %[phi{j}], %[{a_sym}], %[b{j}]\\n\\t")

    outs = []
    ins = [f"[{a_sym}] \"v\"({a_sym})"]
    for j in range(n):
        outs += [f"[plo{j}] \"=&v\"(plo{j})", f"[phi{j}] \"=&v\"(phi{j})"]
        ins.append(f"[b{j}] \"v\"(b{j})")

    lines.append("    __asm volatile(\n        \"")
    lines.append("".join(asm).rstrip("\\n\\t"))
    lines.append("\"\n        : " + ", ".join(outs))
    lines.append("\n        : " + ", ".join(ins))
    lines.append("\n        : );\n")

    for j in range(n):
        lines.append(
            f"    {{ ulong uv = (ulong)tj{j} + (ulong)plo{j} + ((ulong)phi{j} << 32) + carry; "
            f"t[{t_store[j]}] = (uint)uv; carry = uv >> 32; }}\n"
        )
    lines.append("    return carry;\n")
    lines.append("}\n\n")
    return "".join(lines)


def main() -> None:
    parts = [HEADER]
    parts.append(emit_mul_block8("asm_mac_pass1_block8_0", "ai", "B", list(range(8)), list(range(8)), list(range(8))))
    parts.append(emit_mul_block8("asm_mac_pass1_block8_8", "ai", "B", list(range(8, 16)), list(range(8, 16)), list(range(8, 16))))
    parts.append(emit_mul_block8("asm_mac_pass2_block8_1", "m", "N", list(range(1, 9)), list(range(8)), list(range(1, 9))))
    parts.append(
        emit_mul_block8(
            "asm_mac_pass2_block7_9",
            "m",
            "N",
            list(range(9, 16)),
            list(range(8, 15)),
            list(range(9, 16)),
        )
    )
    parts.append("#endif // MONT_MUL_ASM_ENABLE && __AMDGCN__\n")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
