"""Generate deterministic reference FFT capacities from Prime95 mult.asm.

These are reporting reference sizes, not measurements of the executing backend.
No result file, account data or result checksum is read or emitted.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]


def read_table(path, table='zjmptable'):
    rows = [];active = False
    for line in path.read_text().splitlines():
        label = re.match(r'([xyz]jmptablep?)\s+DD', line)
        if label:active = label.group(1) == table
        row = re.search(r'\bPRCSTRT\s+(\d+),\s*(\d+),', line)
        if active and row:rows.append(tuple(map(int, row.groups())))
    if not rows or any(a[0] >= b[0] or a[1] >= b[1] for a, b in zip(rows, rows[1:])):
        raise ValueError('FFT table must contain strictly increasing capacities and lengths')
    return rows


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=ROOT/'.refactor/p95v3106b01.source/gwnum/mult.asm')
    p.add_argument('--check', action='store_true')
    args = p.parse_args();rows = read_table(args.source)
    text = '\n'.join(['// Generated by tools/gen/generate_p95_fft_reference.py; do not edit.',
        '// Prime95 31.6 gwnum/mult.asm, zjmptable (cyclic AVX-512 capacity reference).',
        '#pragma once', '#include <cstdint>', 'namespace ecm_results {',
        'struct FftCapacity {uint64_t max_exponent;uint32_t length;};',
        'inline constexpr FftCapacity p95_fft_capacities[]={']+
        [f'    {{{limit}ull,{length}u}},' for limit, length in rows]+
        ['};', '} // namespace ecm_results', ''])
    dest = ROOT/'src/core/generated/p95_fft_reference.h'
    if args.check:
        if dest.read_text() != text:raise ValueError('stale Prime95 FFT reference')
    else:dest.write_text(text, encoding='utf-8')
    print('FFT reference rows:', len(rows))


if __name__ == '__main__':main()
