#!/usr/bin/env python3
"""Generate fully-unrolled mp_sub_mod for fixed limb counts (bench only)."""

from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "kernels/opencl/bench/mp_addsub/generated/sub_fused_unroll_manual.cl"

HEADER = """// AUTO-GENERATED by tools/gen_mp_sub_mod_unroll.py —do not edit.
// Full unroll of mp_sub_mod: scalar temps, no inner loops.

#ifndef MAX_LIMBS
#define MAX_LIMBS 128
#endif
"""


def emit_limb_block(i: int) -> str:
    return (
        f"    w = (ulong)a{i} - (ulong)b{i} - br; uint r{i} = (uint)w; "
        f"br = ((ulong)a{i} < (ulong)b{i} + br) ? 1ul : 0ul;\n"
    )


def emit_fix_block(i: int) -> str:
    return f"        s = (ulong)r{i} + (ulong)n{i} + c; c = s >> 32; r{i} = (uint)s;\n"


def emit_function(limbs: int) -> str:
    lines = [
        f"inline void mp_sub_mod_u{limbs}(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
    ]
    for i in range(limbs):
        lines.append(f"    uint a{i}=a[{i}], b{i}=b[{i}], n{i}=N[{i}];\n")
    lines.append("    ulong br = 0ul, w, s, c;\n")
    for i in range(limbs):
        lines.append(emit_limb_block(i))
    lines.append("    if (br != 0ul) {\n")
    lines.append("        c = 0ul;\n")
    for i in range(limbs):
        lines.append(emit_fix_block(i))
    lines.append("    }\n")
    for i in range(limbs):
        lines.append(f"    r[{i}] = r{i};\n")
    lines.append("}\n\n")
    return "".join(lines)


def emit_kernel_priv(limbs: int) -> str:
    return f"""
#if MAX_LIMBS == {limbs}
__kernel void ecm_mp_sub_mod_fused_unroll_priv(
    __global const uint *a,
    __global const uint *b,
    __global const uint *n,
    __global uint *out,
    uint limbs)
{{
    if (limbs != {limbs}u) return;
    uint gid = get_global_id(0);
    uint base = gid * {limbs}u;
    uint x[MAX_LIMBS], y[MAX_LIMBS], m[MAX_LIMBS], r[MAX_LIMBS];
    for (uint i = 0u; i < {limbs}u; ++i) {{
        x[i] = a[base + i];
        y[i] = b[base + i];
        m[i] = n[base + i];
    }}
    mp_sub_mod_u{limbs}(r, x, y, m);
    for (uint i = 0u; i < {limbs}u; ++i) {{
        out[base + i] = r[i];
    }}
}}
#endif

"""


def emit_kernel(limbs: int) -> str:
    load_a = "".join(f"    uint a{i} = a[base + {i}u];\n" for i in range(limbs))
    load_b = "".join(f"    uint b{i} = b[base + {i}u];\n" for i in range(limbs))
    load_n = "".join(f"    uint n{i} = n[base + {i}u];\n" for i in range(limbs))
    store = "".join(f"    out[base + {i}u] = r{i};\n" for i in range(limbs))

    body = f"""
#if MAX_LIMBS == {limbs}
__kernel void ecm_mp_sub_mod_fused_unroll(
    __global const uint *a,
    __global const uint *b,
    __global const uint *n,
    __global uint *out,
    uint limbs)
{{
    if (limbs != {limbs}u) return;
    uint gid = get_global_id(0);
    uint base = gid * {limbs}u;
{load_a}{load_b}{load_n}    ulong br = 0ul, w, s, c;
"""
    for i in range(limbs):
        body += emit_limb_block(i)
    body += """    if (br != 0ul) {
        c = 0ul;
"""
    for i in range(limbs):
        body += emit_fix_block(i)
    body += f"""    }}
{store}}}
#endif

"""
    return body


def main() -> None:
    limb_counts = [8, 16, 64, 128, 256]
    parts = [HEADER]
    for n in limb_counts:
        parts.append(f"// --- {n} limbs ({n * 32} bit) ---\n")
        parts.append(emit_function(n))
    for n in limb_counts:
        parts.append(emit_kernel_priv(n))
    for n in limb_counts:
        parts.append(emit_kernel(n))
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
