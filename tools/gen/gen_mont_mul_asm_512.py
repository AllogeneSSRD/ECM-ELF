#!/usr/bin/env python3
"""Generate ASM-assisted mont_mul_priv_unroll_only_512 (CIOS, 16 limbs)."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "kernels/opencl/bench/mont_mul_asm_512_generated.cl"

LIMBS = 16
HEADER = """// AUTO-GENERATED by tools/gen_mont_mul_asm_512.py —do not edit.
// ASM-assisted CIOS mont mul (512-bit / 16 limbs).
// Requires mont_mul_asm_fused.cl; optional mont_mul_asm_block8_generated.cl when inline=0.

#ifndef MONT_OPT2_FIXED_LIMBS
#define MONT_OPT2_FIXED_LIMBS 16u
#endif

#if defined(MONT_MUL_ASM_ENABLE) && defined(__AMDGCN__)

"""


def emit_init() -> str:
    lines = ["    uint t[MONT_OPT2_FIXED_LIMBS + 2u];\n"]
    for i in range(LIMBS + 2):
        lines.append(f"    t[{i}] = 0u;\n")
    lines.append("    uint B[MONT_OPT2_FIXED_LIMBS];\n")
    lines.append("    uint N[MONT_OPT2_FIXED_LIMBS];\n")
    for j in range(LIMBS):
        lines.append(f"    B[{j}] = b[base + {j}u];\n")
        lines.append(f"    N[{j}] = n[{j}];\n")
    return "".join(lines)


def emit_inline_mul_block(a_sym: str, arr_sym: str, t_load: list[int], t_store: list[int], b_idx: list[int], tag: str) -> str:
    n = len(t_load)
    lines = ["        {\n"]
    for j in range(n):
        lines.append(f"        uint plo{tag}{j}, phi{tag}{j};\n")
    for j in range(n):
        lines.append(f"        uint b{tag}{j} = {arr_sym}[{b_idx[j]}];\n")
        lines.append(f"        uint tj{tag}{j} = t[{t_load[j]}];\n")

    asm = []
    for j in range(n):
        asm.append(f"v_mul_lo_u32    %[plo{tag}{j}], %[{a_sym}], %[b{tag}{j}]\\n\\t")
        asm.append(f"v_mul_hi_u32    %[phi{tag}{j}], %[{a_sym}], %[b{tag}{j}]\\n\\t")

    outs = []
    ins = [f"[{a_sym}] \"v\"({a_sym})"]
    for j in range(n):
        outs += [f"[plo{tag}{j}] \"=&v\"(plo{tag}{j})", f"[phi{tag}{j}] \"=&v\"(phi{tag}{j})"]
        ins.append(f"[b{tag}{j}] \"v\"(b{tag}{j})")

    lines.append("        __asm volatile(\n            \"")
    lines.append("".join(asm).rstrip("\\n\\t"))
    lines.append("\"\n            : " + ", ".join(outs))
    lines.append("\n            : " + ", ".join(ins))
    lines.append("\n            : );\n")

    for j in range(n):
        lines.append(
            f"        {{ ulong uv = (ulong)tj{tag}{j} + (ulong)plo{tag}{j} + ((ulong)phi{tag}{j} << 32) + carry; "
            f"t[{t_store[j]}] = (uint)uv; carry = uv >> 32; }}\n"
        )
    lines.append("        }\n")
    return "".join(lines)


def emit_pass1(inline: bool) -> str:
    lines = ["        ulong carry = 0ul;\n"]
    if inline:
        lines.append(emit_inline_mul_block("ai", "B", list(range(8)), list(range(8)), list(range(8)), "p1a"))
        lines.append(emit_inline_mul_block("ai", "B", list(range(8, 16)), list(range(8, 16)), list(range(8, 16)), "p1b"))
    else:
        lines.append("        carry = asm_mac_pass1_block8_0(carry, ai, t, B);\n")
        lines.append("        carry = asm_mac_pass1_block8_8(carry, ai, t, B);\n")
    lines.append(
        f"        {{ ulong top = (ulong)t[{LIMBS}] + carry; "
        f"t[{LIMBS}] = (uint)top; "
        f"t[{LIMBS + 1}] = (uint)(top >> 32); }}\n"
    )
    return "".join(lines)


def emit_pass2(inline: bool) -> str:
    lines = [
        "        uint m = (uint)((ulong)t[0] * (ulong)np0);\n",
        "        carry = asm_red_step0_carry(t[0], m, N[0]);\n",
    ]
    if inline:
        lines.append(emit_inline_mul_block("m", "N", list(range(1, 9)), list(range(0, 8)), list(range(1, 9)), "p2a"))
        lines.append(emit_inline_mul_block("m", "N", list(range(9, 16)), list(range(8, 15)), list(range(9, 16)), "p2b"))
    else:
        lines.append("        carry = asm_mac_pass2_block8_1(carry, m, t, N);\n")
        lines.append("        carry = asm_mac_pass2_block7_9(carry, m, t, N);\n")
    lines.append(
        f"        {{ ulong top = (ulong)t[{LIMBS}] + carry; "
        f"t[{LIMBS - 1}] = (uint)top; "
        f"top = (ulong)t[{LIMBS + 1}] + (top >> 32); "
        f"t[{LIMBS}] = (uint)top; "
        f"t[{LIMBS + 1}] = (uint)(top >> 32); }}\n"
    )
    return "".join(lines)


def emit_outer(i: int, inline: bool) -> str:
    return (
        f"    // outer i={i}\n"
        f"    {{\n"
        f"        uint ai = a[base + {i}u];\n"
        + emit_pass1(inline)
        + emit_pass2(inline)
        + "    }\n"
    )


def emit_subtract() -> str:
    lines = ["    ulong borrow = 0ul;\n", "    uint D[MONT_OPT2_FIXED_LIMBS];\n"]
    for i in range(LIMBS):
        lines.append(
            f"    {{ ulong tv = (ulong)t[{i}]; ulong nv = (ulong)N[{i}]; "
            f"ulong w = tv - nv - borrow; D[{i}] = (uint)w; "
            f"borrow = (tv < nv + borrow) ? 1ul : 0ul; }}\n"
        )
    lines.append(
        "    uint need_sub = (t[MONT_OPT2_FIXED_LIMBS] != 0u || "
        "t[MONT_OPT2_FIXED_LIMBS + 1u] != 0u) ? 1u : 0u;\n"
    )
    lines.append("    need_sub = (borrow == 0u) ? 1u : need_sub;\n")
    lines.append("    uint mask = 0u - need_sub;\n")
    for i in range(LIMBS):
        lines.append(
            f"    out[base + {i}] = (D[{i}] & mask) | (t[{i}] & ~mask);\n"
        )
    return "".join(lines)


def emit_body(inline: bool = True) -> str:
    parts = [
        HEADER,
        "static inline void mont_mul_priv_unroll_only_512_asm_body(\n",
        "    __global uint *out,\n",
        "    __global const uint *a,\n",
        "    __global const uint *b,\n",
        "    __constant uint *n,\n",
        "    uint base,\n",
        "    uint np0)\n",
        "{\n",
        emit_init(),
    ]
    for i in range(LIMBS):
        parts.append(emit_outer(i, inline))
    parts.append(emit_subtract())
    parts.append("}\n\n")
    return "".join(parts)


def emit_bench_kernel() -> str:
    return """__kernel void ecm_mont_mul_priv_unroll_only_512_asm_bench(__global const uint *a,
                                                             __global const uint *b,
                                                             __constant uint *n,
                                                             __global uint *out,
                                                             __constant uint *np0_ptr,
                                                             uint limbs, uint iterations) {
    if (limbs != MONT_OPT2_FIXED_LIMBS) {
        return;
    }
    uint gid = get_global_id(0);
    uint base = gid * limbs;
    uint np0 = np0_ptr[0];
    for (uint it = 0u; it < iterations; ++it) {
        if (it == 0u) {
            mont_mul_priv_unroll_only_512_asm_body(out, a, b, n, base, np0);
        } else {
            mont_mul_priv_unroll_only_512_asm_body(out, out, b, n, base, np0);
        }
    }
}

#endif // MONT_MUL_ASM_ENABLE && __AMDGCN__
"""


def main() -> None:
    OUT.write_text(emit_body(inline=False) + emit_bench_kernel(), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
