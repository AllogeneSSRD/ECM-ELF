#!/usr/bin/env python3
"""Generate fully-unrolled mont_mul_priv_unroll_only_512 (CIOS, 16 limbs, no loops)."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "kernels/opencl/bench/mont_mul_unroll_only_512_manual_generated.cl"

LIMBS = 16
HEADER = """// AUTO-GENERATED by tools/gen_mont_mul_unroll_only_512_manual.py —do not edit.
// Full manual unroll of mont_mul_priv_unroll_only_512_body (512-bit / 16 limbs).

#ifndef MONT_OPT2_FIXED_LIMBS
#define MONT_OPT2_FIXED_LIMBS 16u
#endif

"""


def emit_init() -> str:
    lines = ["    uint t[MONT_OPT2_FIXED_LIMBS + 2u];\n"]
    for i in range(LIMBS + 2):
        lines.append(f"    t[{i}] = 0u;\n")
    lines.append("    uint B[MONT_OPT2_FIXED_LIMBS];\n")
    lines.append("    uint N[MONT_OPT2_FIXED_LIMBS];\n")
    for j in range(LIMBS):
        lines.append(f"    B[{j}] = b[base + {j}u];\n")
        lines.append(f"    N[{j}] = n[{j}];\n")
    return "".join(lines)


def emit_pass1(i: int) -> str:
    lines = [f"        ulong carry = 0ul;\n"]
    for j in range(LIMBS):
        lines.append(
            f"        {{ ulong uv = (ulong)t[{j}] + (ulong)ai * (ulong)B[{j}] + carry; "
            f"t[{j}] = (uint)uv; carry = uv >> 32; }}\n"
        )
    lines.append(
        f"        {{ ulong top = (ulong)t[{LIMBS}] + carry; "
        f"t[{LIMBS}] = (uint)top; t[{LIMBS + 1}] = (uint)(top >> 32); }}\n"
    )
    return "".join(lines)


def emit_pass2() -> str:
    lines = [
        "        uint m = (uint)((ulong)t[0] * (ulong)np0);\n",
        "        { ulong uv0 = (ulong)t[0] + (ulong)m * (ulong)N[0]; carry = uv0 >> 32; }\n",
    ]
    for j in range(1, LIMBS):
        lines.append(
            f"        {{ ulong uv = (ulong)t[{j}] + (ulong)m * (ulong)N[{j}] + carry; "
            f"t[{j - 1}] = (uint)uv; carry = uv >> 32; }}\n"
        )
    lines.append(
        f"        {{ ulong top = (ulong)t[{LIMBS}] + carry; "
        f"t[{LIMBS - 1}] = (uint)top; "
        f"top = (ulong)t[{LIMBS + 1}] + (top >> 32); "
        f"t[{LIMBS}] = (uint)top; t[{LIMBS + 1}] = (uint)(top >> 32); }}\n"
    )
    return "".join(lines)


def emit_outer(i: int) -> str:
    body = [
        f"    // outer i={i}\n",
        f"    {{\n",
        f"        uint ai = a[base + {i}u];\n",
        emit_pass1(i),
        emit_pass2(),
        "    }\n",
    ]
    return "".join(body)


def emit_subtract() -> str:
    lines = ["    ulong borrow = 0ul;\n", "    uint D[MONT_OPT2_FIXED_LIMBS];\n"]
    for i in range(LIMBS):
        lines.append(
            f"    {{ ulong tv = (ulong)t[{i}]; ulong nv = (ulong)N[{i}]; "
            f"ulong w = tv - nv - borrow; D[{i}] = (uint)w; "
            f"borrow = (tv < nv + borrow) ? 1ul : 0ul; }}\n"
        )
    lines.append(
        "    uint need_sub = (t[MONT_OPT2_FIXED_LIMBS] != 0u || "
        "t[MONT_OPT2_FIXED_LIMBS + 1u] != 0u) ? 1u : 0u;\n"
    )
    lines.append("    need_sub = (borrow == 0u) ? 1u : need_sub;\n")
    lines.append("    uint mask = 0u - need_sub;\n")
    for i in range(LIMBS):
        lines.append(
            f"    out[base + {i}] = (D[{i}] & mask) | (t[{i}] & ~mask);\n"
        )
    return "".join(lines)


def emit_body() -> str:
    parts = [
        "static inline void mont_mul_priv_unroll_only_512_manual_body(\n",
        "    __global uint *out,\n",
        "    __global const uint *a,\n",
        "    __global const uint *b,\n",
        "    __constant uint *n,\n",
        "    uint base,\n",
        "    uint np0)\n",
        "{\n",
        emit_init(),
    ]
    for i in range(LIMBS):
        parts.append(emit_outer(i))
    parts.append(emit_subtract())
    parts.append("}\n\n")
    return "".join(parts)


def emit_raw_kernel() -> str:
    return """__kernel void cgbn_mont_mul_unroll_only_512_manual(
    __global const uint *a, __global const uint *b,
    __constant uint *n, __global uint *out,
    __constant uint *np0_ptr)
{
    uint idx = get_global_id(0);
    uint base = idx * MONT_OPT2_FIXED_LIMBS;
    uint np0 = np0_ptr[0];
    mont_mul_priv_unroll_only_512_manual_body(out, a, b, n, base, np0);
}

"""


def main() -> None:
    content = HEADER + emit_body() + emit_raw_kernel()
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT} ({len(content.splitlines())} lines)")


if __name__ == "__main__":
    main()
