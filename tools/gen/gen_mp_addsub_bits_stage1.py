#!/usr/bin/env python3
"""Generate stage1 add/sub bit-width paths under add_mod/ and sub_mod/.
Also writes common/asm_common.h.cl (shared AMDGCN inline-asm infrastructure)."""

from __future__ import annotations

import re
from pathlib import Path

from mp_asm_block_gen import emit_add_block, emit_c_fix_add, emit_sub_block


def _collapse_blanks(s: str) -> str:
    """Collapse runs of 3+ newlines down to exactly 2 (one blank line)."""
    return re.sub(r"\n\n\n+", "\n\n", s.strip("\n")) + "\n"


ROOT = Path(__file__).resolve().parents[2]
ADD_MOD = ROOT / "kernels/opencl/add_mod"
SUB_MOD = ROOT / "kernels/opencl/sub_mod"
COMMON = ROOT / "kernels/opencl/common"

# ── Threshold: limbs >= this value use loop-of-block16 instead of monolithic ASM
ASM_LOOP_THRESHOLD = 48  # 1536-bit and above

WIDTHS = (
    (128, 4, 128),
    (192, 6, 192),
    (256, 8, 256),
    (384, 12, 378),
    (512, 16, 504),
    (768, 24, 768),
    (1024, 32, 1024),
    (1536, 48, 1536),
    (2048, 64, 2048),
    (2560, 80, 2560),
    (3072, 96, 3072),
    (3584, 112, 3584),
    (4096, 128, 4096),
    (4608, 144, 4608),
    (5120, 160, 5120),
    (5632, 176, 5632),
    (6144, 192, 6144),
    (6656, 208, 6656),
    (7168, 224, 7168),
    (7680, 240, 7680),
    (8192, 256, 8192),
)

HEADER = "// AUTO-GENERATED by tools/gen_mp_addsub_bits_stage1.py - do not edit.\n"


def emit_add_unroll(limbs: int, bits: int) -> str:
    guard = f"ADD_MOD_UNROLL_{bits}B_BODY_DEFINED"
    lines = [
        f"#ifndef {guard}\n",
        f"#define {guard}\n",
        f"static inline void add_mod_unroll_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
    ]
    if limbs < 112:
        # Flat: each limb is a separate block.  Up to 96 limbs (3072b) the
        # compiler pipelines this well.  At 112+ limbs (3584b+) block-fusing
        # avoids VGPR overflow.
        lines.append("    ulong carry_add = 0ul;\n")
        lines.append("    ulong carry_sub = 1ul;\n")
        for i in range(limbs):
            lines.append(
                f"    {{\n"
                f"        ulong sum = (ulong)a[{i}] + (ulong)b[{i}] + carry_add;\n"
                f"        carry_add = sum >> 32;\n"
                f"        ulong temp = (ulong)(uint)sum + (ulong)(~N[{i}]) + carry_sub;\n"
                f"        carry_sub = temp >> 32;\n"
                f"        r[{i}] = (uint)temp;\n"
                f"    }}\n"
            )
        lines.append("    if ((carry_add | carry_sub) != 0ul) {\n        return;\n    }\n")
        lines.append("    ulong c = 0ul;\n")
        for i in range(limbs):
            lines.append(
                f"    {{\n"
                f"        ulong s = (ulong)r[{i}] + (ulong)N[{i}] + c;\n"
                f"        r[{i}] = (uint)s;\n"
                f"        c = s >> 32;\n"
                f"    }}\n"
            )
    else:
        # Block-fused: 32-element blocks with inner #pragma unroll 32.
        # Prevents NVIDIA compiler from choking on massive flat inline expansion.
        # For >8192b, use larger blocks to avoid excessive code size.
        n_blk = limbs // 32
        n_rem = limbs % 32
        lines.append("    ulong carry_add = 0ul;\n")
        lines.append("    ulong carry_sub = 1ul;\n")
        if n_blk > 0:
            lines.append("    #pragma unroll\n")
            lines.append(f"    for (uint blk = 0u; blk < {n_blk}u; ++blk) {{\n")
            lines.append( "        uint off = blk * 32u;\n")
            lines.append( "        #pragma unroll 32\n")
            lines.append( "        for (uint j = 0u; j < 32u; ++j) {\n")
            lines.append( "            uint i = off + j;\n")
            lines.append( "            ulong sum = (ulong)a[i] + (ulong)b[i] + carry_add;\n")
            lines.append( "            carry_add = sum >> 32;\n")
            lines.append( "            ulong temp = (ulong)(uint)sum + (ulong)(~N[i]) + carry_sub;\n")
            lines.append( "            carry_sub = temp >> 32;\n")
            lines.append( "            r[i] = (uint)temp;\n")
            lines.append( "        }\n")
            lines.append( "    }\n")
        if n_rem > 0:
            lines.append(f"    {{ uint off = {n_blk} * 32u;\n")
            for i in range(n_rem):
                lines.append(
                    f"        {{ uint i = off + {i};\n"
                    f"            ulong sum = (ulong)a[i] + (ulong)b[i] + carry_add;\n"
                    f"            carry_add = sum >> 32;\n"
                    f"            ulong temp = (ulong)(uint)sum + (ulong)(~N[i]) + carry_sub;\n"
                    f"            carry_sub = temp >> 32;\n"
                    f"            r[i] = (uint)temp; }}\n"
                )
            lines.append("    }\n")
        lines.append("    if ((carry_add | carry_sub) != 0ul) {\n        return;\n    }\n")
        lines.append("    ulong c = 0ul;\n")
        if limbs <= 128:
            lines.append(f"    #pragma unroll 32\n")
        else:
            lines.append(f"    // NVIDIA compiler crash avoidance: no unroll for large limb counts\n")
        lines.append(f"    for (uint i = 0u; i < {limbs}u; ++i) {{\n")
        lines.append( "        ulong s = (ulong)r[i] + (ulong)N[i] + c;\n")
        lines.append( "        r[i] = (uint)s;\n")
        lines.append( "        c = s >> 32;\n")
        lines.append( "    }\n")
    lines.append("}\n#endif\n\n")
    return "".join(lines)


def emit_sub_unroll(limbs: int, bits: int) -> str:
    guard = f"SUB_MOD_UNROLL_{bits}B_BODY_DEFINED"
    lines = [
        f"#ifndef {guard}\n",
        f"#define {guard}\n",
        f"static inline int sub_mod_unroll_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
    ]
    if limbs < 112:
        # Flat: each limb is a separate block (see add_unroll comment above).
        lines.append("    ulong br = 0ul;\n")
        for i in range(limbs):
            lines.append(
                f"    {{\n"
                f"        ulong av = (ulong)a[{i}];\n"
                f"        ulong bv = (ulong)b[{i}];\n"
                f"        ulong w = av - bv - br;\n"
                f"        r[{i}] = (uint)w;\n"
                f"        br = (av < bv + br) ? 1ul : 0ul;\n"
                f"    }}\n"
            )
        lines.append("    if (br != 0ul) {\n        ulong c = 0ul;\n")
        for i in range(limbs):
            lines.append(
                f"        {{\n"
                f"            ulong s = (ulong)r[{i}] + (ulong)N[{i}] + c;\n"
                f"            r[{i}] = (uint)s;\n"
                f"            c = s >> 32;\n"
                f"        }}\n"
            )
        lines.append("        return 1;\n    }\n    return 0;\n}\n#endif\n\n")
    else:
        n_blk = limbs // 32
        n_rem = limbs % 32
        lines.append("    ulong br = 0ul;\n")
        if n_blk > 0:
            lines.append("    #pragma unroll\n")
            lines.append(f"    for (uint blk = 0u; blk < {n_blk}u; ++blk) {{\n")
            lines.append( "        uint off = blk * 32u;\n")
            lines.append( "        #pragma unroll 32\n")
            lines.append( "        for (uint j = 0u; j < 32u; ++j) {\n")
            lines.append( "            uint i = off + j;\n")
            lines.append( "            ulong av = (ulong)a[i];\n")
            lines.append( "            ulong bv = (ulong)b[i];\n")
            lines.append( "            ulong w = av - bv - br;\n")
            lines.append( "            r[i] = (uint)w;\n")
            lines.append( "            br = (av < bv + br) ? 1ul : 0ul;\n")
            lines.append( "        }\n")
            lines.append( "    }\n")
        if n_rem > 0:
            lines.append(f"    {{ uint off = {n_blk} * 32u;\n")
            for i in range(n_rem):
                lines.append(
                    f"        {{ uint i = off + {i};\n"
                    f"            ulong av = (ulong)a[i];\n"
                    f"            ulong bv = (ulong)b[i];\n"
                    f"            ulong w = av - bv - br;\n"
                    f"            r[i] = (uint)w;\n"
                    f"            br = (av < bv + br) ? 1ul : 0ul; }}\n"
                )
            lines.append("    }\n")
        lines.append("    if (br != 0ul) {\n        ulong c = 0ul;\n")
        if limbs <= 128:
            lines.append(f"    #pragma unroll 32\n")
        else:
            lines.append(f"    // NVIDIA compiler crash avoidance: no unroll for large limb counts\n")
        lines.append(f"    for (uint i = 0u; i < {limbs}u; ++i) {{\n")
        lines.append( "        ulong s = (ulong)r[i] + (ulong)N[i] + c;\n")
        lines.append( "        r[i] = (uint)s;\n")
        lines.append( "        c = s >> 32;\n")
        lines.append( "    }\n")
        lines.append("        return 1;\n    }\n    return 0;\n}\n#endif\n\n")
    return "".join(lines)


def emit_add_asm_body(limbs: int, bits: int) -> str:
    if limbs < ASM_LOOP_THRESHOLD:
        return (
            f"static inline void add_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n"
            f"    uint ca = 0u, cs = 1u;\n"
            f"    asm_fused_block{limbs}_priv(a, b, N, r, ca, cs, &ca, &cs);\n"
            f"}}\n\n"
        )
    # >=threshold: use C fused loop with block-loop ASM blocks and global fix.
    # The ASM fused_block functions internally call c_fix_add_n32 which creates
    # per-block isolated fix. We override by writing a global fix at the end
    # AND using ASM blocks with fix_in_block=False to avoid double-add.
    blk32 = limbs // 32
    rem16 = (limbs % 32) // 16
    lines = [
        f"static inline void add_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
        f"    uint ca = 0u, cs = 1u;\n",
    ]
    for k in range(blk32):
        off = k * 32
        lines.append(f"    asm_fused_block32_priv_nofix(a + {off}, b + {off}, N + {off}, r + {off}, ca, cs, &ca, &cs);\n")
    if rem16:
        off = blk32 * 32
        lines.append(f"    asm_fused_block16_priv_nofix(a + {off}, b + {off}, N + {off}, r + {off}, ca, cs, &ca, &cs);\n")
    # Global fix: (ca|cs)==0 → r += N with full {limbs}-limb carry chain
    lines.append(f"    if ((ca | cs) == 0u) {{\n")
    lines.append( "        ulong c = 0ul;\n")
    for i in range(limbs):
        lines.append(f"        c = (ulong)r[{i}] + (ulong)N[{i}] + c; r[{i}] = (uint)c; c >>= 32;\n")
    lines.append( "    }\n")
    lines.append("}\n\n")
    return "".join(lines)


def emit_sub_asm_body(limbs: int, bits: int) -> str:
    if limbs < ASM_LOOP_THRESHOLD:
        return (
            f"static inline int sub_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n"
            f"    uint br = 0u;\n"
            f"    asm_sub_fused_block{limbs}_priv(a, b, N, r, br, &br);\n"
            f"    return br != 0u ? 1 : 0;\n"
            f"}}\n\n"
        )
    blk32 = limbs // 32
    rem16 = (limbs % 32) // 16
    lines = [
        f"static inline int sub_mod_asm_{bits}b_body(uint *r, const uint *a, const uint *b, const uint *N) {{\n",
        f"    uint br = 0u;\n",
    ]
    for k in range(blk32):
        off = k * 32
        lines.append(f"    asm_sub_fused_block32_priv_nofix(a + {off}, b + {off}, N + {off}, r + {off}, br, &br);\n")
    if rem16:
        off = blk32 * 32
        lines.append(f"    asm_sub_fused_block16_priv_nofix(a + {off}, b + {off}, N + {off}, r + {off}, br, &br);\n")
    # Global fix: br!=0 → r += N with full limb-wide carry chain
    lines.append(f"    if (br != 0u) {{\n")
    lines.append( "        ulong c = 0ul;\n")
    for i in range(limbs):
        lines.append(f"        c = (ulong)r[{i}] + (ulong)N[{i}] + c; r[{i}] = (uint)c; c >>= 32;\n")
    lines.append( "    }\n")
    lines.append(f"    return br != 0u ? 1 : 0;\n")
    lines.append("}\n\n")
    return "".join(lines)


def emit_add_asm_wrapper(bits: int, limbs: int) -> str:
    return (
        f"#if defined(__AMDGCN__)\n"
        f"static inline void add_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                       const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ add_mod_asm_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
        f"#else\n"
        f"static inline void add_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                       const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ add_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
        f"#endif\n"
    )


def emit_sub_asm_wrapper(bits: int, limbs: int) -> str:
    return (
        f"#if defined(__AMDGCN__)\n"
        f"static inline int sub_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                      const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ return sub_mod_asm_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
        f"#else\n"
        f"static inline int sub_mod_asm_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                      const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ return sub_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
        f"#endif\n"
    )


def write_asm_common() -> None:
    """Write shared AMDGCN asm infrastructure with #ifndef guards."""
    lines = [
        HEADER,
        "#if defined(__AMDGCN__)\n\n",
    ]
    # c_fix_add functions for each width — only needed for sizes where
    # asm blocks are emitted (limbs < ASM_LOOP_THRESHOLD). Larger sizes
    # use loop-of-block wrappers with inline fix code.
    for _bits, limbs, _max_n in WIDTHS:
        if limbs >= ASM_LOOP_THRESHOLD:
            continue
        guard = f"ASM_COMMON_C_FIX_ADD_N{limbs}_DEFINED"
        body = _collapse_blanks(emit_c_fix_add(limbs))
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
    # add blocks — fix/nofix only for sizes actually used:
    #   limbs <  ASM_LOOP_THRESHOLD: fix variant  (direct use in per-bit wrapper)
    #   limbs in {16,32}:           nofix variant  (loop-body use by >=threshold wrappers)
    #   limbs >= ASM_LOOP_THRESHOLD: skip entirely (wrappers use loop of block16/block32)
    NOFIX_SIZES = {16, 32}
    for _bits, limbs, _max_n in WIDTHS:
        if limbs >= ASM_LOOP_THRESHOLD:
            continue  # not directly used; loop-body wrappers use block16/block32
        guard = f"ASM_COMMON_FUSED_BLOCK{limbs}_PRIV_DEFINED"
        body = _collapse_blanks(emit_add_block(limbs, global_addr=False, fix_in_block=True))
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
        if limbs in NOFIX_SIZES:
            guard_nf = f"ASM_COMMON_FUSED_BLOCK{limbs}_PRIV_NOFIX_DEFINED"
            body_nf = _collapse_blanks(emit_add_block(limbs, global_addr=False, fix_in_block=False))
            lines.append(f"#ifndef {guard_nf}\n#define {guard_nf}\n{body_nf}#endif\n")
    # sub blocks
    for _bits, limbs, _max_n in WIDTHS:
        if limbs >= ASM_LOOP_THRESHOLD:
            continue
        guard = f"ASM_COMMON_SUB_FUSED_BLOCK{limbs}_PRIV_DEFINED"
        body = _collapse_blanks(emit_sub_block(limbs, global_addr=False, fix_in_block=True))
        lines.append(f"#ifndef {guard}\n#define {guard}\n{body}#endif\n")
        if limbs in NOFIX_SIZES:
            guard_nf = f"ASM_COMMON_SUB_FUSED_BLOCK{limbs}_PRIV_NOFIX_DEFINED"
            body_nf = _collapse_blanks(emit_sub_block(limbs, global_addr=False, fix_in_block=False))
            lines.append(f"#ifndef {guard_nf}\n#define {guard_nf}\n{body_nf}#endif\n")
    lines.append("#endif // __AMDGCN__\n")
    path = COMMON / "asm_common.h.cl"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(lines), encoding="utf-8")
    print(f"Wrote {path}")


def write_add_unroll(bits: int, limbs: int, body: str) -> None:
    path = ADD_MOD / f"add_mod_unroll_{bits}b.cl"
    wrapper = (
        f"static inline void add_mod_unroll_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                          const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ add_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    (void)limbs;\n"
        f"}}\n"
    )
    path.write_text(f"{HEADER}{body}{wrapper}", encoding="utf-8")
    print(f"Wrote {path}")


def write_sub_unroll(bits: int, limbs: int, body: str) -> None:
    path = SUB_MOD / f"sub_mod_unroll_{bits}b.cl"
    wrapper = (
        f"static inline int sub_mod_unroll_{bits}b(uint *r, const uint *a, const uint *b,\n"
        f"                                         const uint *N, uint limbs) {{\n"
        f"    if (limbs == {limbs}u) {{ return sub_mod_unroll_{bits}b_body(r, a, b, N); }}\n"
        f"    return 0;\n"
        f"}}\n"
    )
    path.write_text(f"{HEADER}{body}{wrapper}", encoding="utf-8")
    print(f"Wrote {path}")


def write_add_asm(bits: int, limbs: int, asm_body: str, unroll_body: str) -> None:
    path = ADD_MOD / f"add_mod_asm_{bits}b.cl"
    content = (
        f"{HEADER}"
        # asm_body calls the AMDGCN-only asm_*_priv helpers; guard it so the file
        # still compiles on non-AMD OpenCL compilers (the wrapper below falls back
        # to the portable unroll body when __AMDGCN__ is not defined).
        f"#if defined(__AMDGCN__)\n"
        f"{asm_body}"
        f"#endif\n"
        f"#if !defined(__AMDGCN__)\n"
        f"{unroll_body}"
        f"#endif\n"
        f"{emit_add_asm_wrapper(bits, limbs)}"
    )
    path.write_text(content, encoding="utf-8")
    print(f"Wrote {path}")


def write_sub_asm(bits: int, limbs: int, asm_body: str, unroll_body: str) -> None:
    path = SUB_MOD / f"sub_mod_asm_{bits}b.cl"
    content = (
        f"{HEADER}"
        # asm_body calls the AMDGCN-only asm_*_priv helpers; guard it so the file
        # still compiles on non-AMD OpenCL compilers (the wrapper below falls back
        # to the portable unroll body when __AMDGCN__ is not defined).
        f"#if defined(__AMDGCN__)\n"
        f"{asm_body}"
        f"#endif\n"
        f"#if !defined(__AMDGCN__)\n"
        f"{unroll_body}"
        f"#endif\n"
        f"{emit_sub_asm_wrapper(bits, limbs)}"
    )
    path.write_text(content, encoding="utf-8")
    print(f"Wrote {path}")


def main() -> None:
    # 1. Write shared asm common infrastructure
    write_asm_common()

    # 2. Write per-bit unroll files
    for bits, limbs, _max_n in WIDTHS:
        write_add_unroll(bits, limbs, emit_add_unroll(limbs, bits))
        write_sub_unroll(bits, limbs, emit_sub_unroll(limbs, bits))

    # 3. Write per-bit asm files (no common code; only bodies + wrappers)
    for bits, limbs, _max_n in WIDTHS:
        write_add_asm(bits, limbs, emit_add_asm_body(limbs, bits), emit_add_unroll(limbs, bits))
        write_sub_asm(bits, limbs, emit_sub_asm_body(limbs, bits), emit_sub_unroll(limbs, bits))


if __name__ == "__main__":
    main()
